"""
Write results/: the recorded ladder, climb and pilot runs the lab replays offline.

    uv run python snapshot.py

For every cell with rows it copies the run's rows and adds one small file with
what the lab needs to re-grade and re-price each session without the bulk traces:

    results/<flow>/<cell>/rows.jsonl       results.jsonl, byte for byte
    results/<flow>/<cell>/sessions.jsonl   per row: the final reply and each model request's usage

The rows are named rows.jsonl, never results.jsonl, on purpose: spend.py sums every
results.jsonl under evals/, so a copy under that name would count the spend twice.
Reads hillclimb/ and pilot/ only; never calls the API. tests/test_lab.py checks that
results/ matches what this script writes, so the snapshot can't drift from its source.
"""
from __future__ import annotations

import json
from pathlib import Path

EVALS = Path(__file__).parent
OUT = EVALS / "results"
USAGE_KEYS = ("input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens")
FLOWS = {"ladder": EVALS / "hillclimb" / "ladder", "climb": EVALS / "hillclimb" / "climb"}
KEEP = ("summary.json", "change.md", "change.patch", "system.md")  # small files kept beside the rows

INDEX = """\
# Recorded results

Generated by `uv run python snapshot.py` from `hillclimb/` and `pilot/`. Don't edit by hand.

These are the real runs behind the lab's numbers, so every checkpoint can be replayed
without an API key: `uv run python checkpoint.py all --solution`.

| path | what it is |
|---|---|
| `ladder/state.json` | the walk: cells in visit order, the pre-registered floor, the splits |
| `ladder/<cell>/` | one model × effort cell: `baseline` = Opus 4.8 default, `v1`–`v5` in visit order |
| `climb/state.json`, `climb/<round>/` | the system-prompt hillclimb on Sonnet 5.5 low; `v1/system.md` is the climbed prompt |
| `pilot/<model>-<effort>/` | one-session canaries, run before each new cell |
| `path.svg`, `path.png` | the cost-reduction path chart (`plot_path.py`) |

In each cell:

- `rows.jsonl`: the run's `results.jsonl`, byte for byte: one row per (case, rep) with the
  grade, tokens, `list_cost_usd`, `rate_card_usd`, latency and session metadata.
- `sessions.jsonl`: the same rows in the same order, with only what re-grading and re-pricing
  need: `reply` (the agent's final text, as the grader saw it) and `requests` (each model
  request's token usage).
- `change.md`: why the walk or the climb went there.

The rows are called `rows.jsonl`, not `results.jsonl`, so `spend.py` doesn't count the
same spend twice. The full traces and raw events stay in `hillclimb/` and `pilot/`.
"""


def _lines(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def session(vdir: Path, row: dict) -> dict:
    """The reply the grader saw (assistant turns joined, as regrade.py does) and per-request usage."""
    key = f"{row['prompt_id']}_rep{row['rep']}"
    trace = json.loads((vdir / "traces" / f"{key}.json").read_text())
    reply = "\n".join(t["content"] for t in trace if t["role"] == "assistant")
    requests = [{k: int(e["model_usage"].get(k) or 0) for k in USAGE_KEYS}
                for e in _lines(vdir / "raw" / f"{key}.jsonl") if e.get("type") == "span.model_request_end"]
    return {"prompt_id": row["prompt_id"], "rep": row["rep"], "reply": reply, "requests": requests}


def cell_files(vdir: Path, dest: str) -> dict[str, bytes]:
    out = {f"{dest}/rows.jsonl": (vdir / "results.jsonl").read_bytes()}
    out[f"{dest}/sessions.jsonl"] = "".join(
        json.dumps(session(vdir, r), ensure_ascii=False, separators=(",", ":")) + "\n"
        for r in _lines(vdir / "results.jsonl")).encode()
    for name in KEEP:
        if (vdir / name).exists():
            out[f"{dest}/{name}"] = (vdir / name).read_bytes()
    return out


def build() -> dict[str, bytes]:
    """{path under results/: bytes}, everything except the chart (plot_path.py writes that)."""
    files = {"README.md": INDEX.encode()}
    for name, flow in FLOWS.items():
        files[f"{name}/state.json"] = (flow / "_state.json").read_bytes()
        for vdir in sorted(d for d in flow.iterdir() if (d / "results.jsonl").exists()):
            files.update(cell_files(vdir, f"{name}/{vdir.name}"))
    for vdir in sorted((EVALS / "pilot").glob("*/baseline")):
        if (vdir / "results.jsonl").exists():
            files.update(cell_files(vdir, f"pilot/{vdir.parent.name}"))
    return files


def main() -> None:
    files = build()
    for rel, data in files.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    print(f"wrote {len(files)} files to {OUT.relative_to(EVALS)}/ "
          f"({sum(map(len, files.values())) / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
