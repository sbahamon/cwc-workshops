"""
Write COST_LEDGER.md: accuracy x cost per incident for every cell, and spend by
ledger file against the $50 cap. Every number is recomputed from the
results.jsonl / errors.jsonl files (via walk.cell and spend.py); nothing is typed in.

    uv run python ledger.py

Costs: list_cost is what Managed Agents reports per session and what the cap
enforces; the rate card is the published per-token prices plus runtime
(pricing.py), which is what the Console bill followed (SOURCES.md).
"""
from __future__ import annotations

import json
from pathlib import Path

from spend import CAP_USD, counted, ledger_files, spend_by_file, total_spend
from walk import LADDER, cell, verdict

EVALS = Path(__file__).parent
CLIMB = EVALS / "hillclimb" / "climb"
OUT = EVALS / "COST_LEDGER.md"
NAMES = {"claude-opus-4-8": "Opus 4.8", "claude-sonnet-5-5": "Sonnet 5.5", "claude-haiku-5-5": "Haiku 5.5"}


def pct(p, hw=None):
    return "n/a" if p is None else f"{p:.1%}" + (f" ± {hw:.1%}" if hw is not None else "")


def cells() -> list[tuple[str, str, str, dict]]:
    """(flow label, variant, prompt, cell) for every ladder and climb variant with rows."""
    out = []
    for flow, label in ((LADDER, "ladder"), (CLIMB, "climb")):
        if not flow.exists():
            continue
        names = sorted((d.name for d in flow.iterdir() if d.is_dir() and (d.name == "baseline" or d.name[1:].isdigit())),
                       key=lambda v: -1 if v == "baseline" else int(v[1:]))
        for v in names:
            c = cell(v, flow)
            if not c["rows"]:
                continue
            first = json.loads((flow / v / "results.jsonl").read_text().splitlines()[0])
            out.append((label, v, first["meta"].get("system_sha", "?")[:8], c))
    return out


def roles() -> dict[tuple[str, str], str]:
    r = {}
    for e in json.loads((LADDER / "_state.json").read_text()).get("walk", []):
        r[("ladder", e["variant"])] = e.get("verdict", "")
    if (CLIMB / "_state.json").exists():
        st = json.loads((CLIMB / "_state.json").read_text())
        r[("climb", "baseline")] = "copy of ladder v1 (not billed again)"
        for e in st.get("rounds", []):
            r[("climb", e["variant"])] = e.get("kept", "")
    return r


def main() -> None:
    floor = json.loads((LADDER / "_state.json").read_text())["floor"]
    base = cell("baseline")
    role = roles()
    lines = ["# Cost ledger", "",
             "Generated by `uv run python ledger.py` from the results files; don't edit by hand.", "",
             "## Accuracy × cost per incident", "",
             "Floor (pre-registered, docs/plan.md C0.3): root cause on train+test within 10 points of the "
             f"Opus 4.8 baseline (≥ {base['root_cause_tt'] - 0.10:.1%}), `reg-verbatim` right on every rep, format ≥ 95%.", "",
             "| flow | cell | model, effort | prompt sha | rows | root cause train+test (95% CI) | format (95% CI) "
             "| reg-verbatim | ¢/incident rate card | ¢/incident list_cost | floor | note |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for flow, v, sha, c in cells():
        model = ", ".join(NAMES.get(m, m) for m in c["models"])
        eff = "/".join(c["effort_echoed"])
        fl = "reference" if (flow, v) == ("ladder", "baseline") else \
            ("PASS" if verdict(c, base, floor)["pass"] else "FAIL")
        lines.append(f"| {flow} | {v} | {model}, {eff} | `{sha}` | {c['rows']} | {pct(c['root_cause_tt'], c['root_cause_tt_hw'])} "
                     f"| {pct(c['format'], c['format_hw'])} | {c['reg_verbatim']} | {c['rate_card_per_incident'] * 100:.2f} "
                     f"| {c['list_per_incident'] * 100:.2f} | {fl} | {role.get((flow, v), '')} |")
    lst, card = spend_by_file(), spend_by_file(column="rate_card")
    lines += ["", "## Spend by ledger file", "",
              "Failed attempts (`errors.jsonl`) are billed and counted. Copied rows (`meta.copied_from`) and fake rows are not.", "",
              "| ledger file | list_cost | rate card |", "|---|---|---|"]
    for f in sorted(lst):
        lines.append(f"| `{f}` | ${lst[f]:.2f} | ${card.get(f, 0):.4f} |")
    total = total_spend()
    raw = round(sum(float(r.get("list_cost_usd") or 0) for p in ledger_files() for r in map(json.loads, filter(str.strip, p.read_text().splitlines())) if counted(r)), 2)
    assert abs(raw - total) < 0.005, (raw, total)
    lines += [f"| **total** | **${total:.2f}** | **${sum(card.values()):.2f}** |", "",
              f"Cap: ${CAP_USD:.2f} on list_cost; {total / CAP_USD:.0%} used, ${CAP_USD - total:.2f} left. "
              "The total matches `spend.py` and the raw sum of `list_cost_usd` over every counted row.", "",
              "Haiku 5.5 note: its session `list_cost` reads about 5× what the Console billed (SOURCES.md), "
              "so Haiku's list column overstates what was actually billed; the cap counts it at list_cost anyway."]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.name}: total ${total:.2f} list")


if __name__ == "__main__":
    main()
